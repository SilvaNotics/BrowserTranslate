import { mkdir, writeFile } from 'node:fs/promises';

// Maintenance command only. Normal builds use the committed local data.
const source = 'https://raw.githubusercontent.com/BYVoid/OpenCC/ver.1.1.9/';
async function read(path) {
  const response = await fetch(source + path);
  if (!response.ok) throw new Error('OpenCC data download failed: ' + response.status);
  return response.text();
}
const [simplified, traditional, license] = await Promise.all([
  read('data/dictionary/STCharacters.txt'),
  read('data/dictionary/TSCharacters.txt'),
  read('LICENSE'),
]);
function changedCharacters(dictionary) {
  return [
    ...new Set(
      dictionary.split('\n').flatMap((line) => {
        if (!line || line.startsWith('#')) return [];
        const [character, targets] = line.split('\t');
        return character && targets && targets.split(' ')[0] !== character ? [character] : [];
      }),
    ),
  ].join('');
}
await mkdir('src/core/data/opencc', { recursive: true });
await writeFile('src/core/data/opencc/LICENSE', license.trimEnd() + '\n');
await writeFile(
  'src/core/data/opencc/characters.ts',
  '// Generated by scripts/update-chinese-variants.mjs from OpenCC 1.1.9.\n' +
    '// Source: ' +
    source +
    'data/dictionary/ (Apache-2.0; see LICENSE).\n' +
    '// Retains characters whose first conversion candidate differs from the source.\n' +
    'export const simplifiedCharacters = new Set(' +
    JSON.stringify(changedCharacters(simplified)) +
    ');\n' +
    'export const traditionalCharacters = new Set(' +
    JSON.stringify(changedCharacters(traditional)) +
    ');\n',
);
console.log('OpenCC character differences and license updated.');
